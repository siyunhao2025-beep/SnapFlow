const fs=require('node:fs'),path=require('node:path')
const root=process.cwd(), pkg=require(path.join(root,'package.json'))
let ok=true; const c=(n,v,d='')=>{console.log(`${v?'PASS':'FAIL'}  ${n}${d?' — '+d:''}`);ok=ok&&!!v}
c('v2 semver',pkg.version==='2.0.0',pkg.version)
c('provider registry',fs.existsSync(path.join(root,'src/main/providers/registry.ts')))
c('provider errors/audit',fs.existsSync(path.join(root,'src/shared/errors.ts'))&&fs.existsSync(path.join(root,'src/main/audit-log.ts')))
c('local OCR',fs.existsSync(path.join(root,'src/main/local-ocr.ts'))&&fs.existsSync(path.join(root,'src/renderer/src/workers/ocr.worker.ts')))
c('semantic/workflow/privacy', ['semantic.ts','workflow.ts','privacy.ts'].every(x=>fs.existsSync(path.join(root,'src/shared',x))))
c('skill marketplace',fs.existsSync(path.join(root,'src/main/skill-marketplace.ts')))
c('cloud gateway',fs.existsSync(path.join(root,'cloud-server/server.mjs'))&&fs.existsSync(path.join(root,'cloud-server/schema.sql')))
c('updater',fs.existsSync(path.join(root,'src/main/updater.ts')))
c('website source',fs.existsSync(path.join(root,'snapflow-website/index.html'))&&fs.statSync(path.join(root,'snapflow-website/index.html')).size<200*1024)
const html=fs.readFileSync(path.join(root,'snapflow-website/index.html'),'utf8')
c('website sections',['features','story','scenes','download','particles'].every(id=>html.includes(id)))
c('NSIS + Portable',JSON.stringify(pkg.build?.win?.target||[]).includes('nsis')&&JSON.stringify(pkg.build?.win?.target||[]).includes('portable'))
c('no obvious secrets',!/(sk-[A-Za-z0-9_-]{20,}|STRIPE_SECRET_KEY\s*[:=]\s*['\"][^<])/i.test(JSON.stringify(pkg)))
if(!ok) process.exit(1)
